
class HostelModel {
  final String name;
  final String location;
  final String city;
  final int price;
  final String sharing;
  final String gender;
  final double rating;

  final bool food;
  final bool wifi;
  final bool ac;
  final bool security;
  final bool parking;
  final bool laundry;

  HostelModel({
    required this.name,
    required this.location,
    required this.city,
    required this.price,
    required this.sharing,
    required this.gender,
    required this.rating,
    required this.food,
    required this.wifi,
    required this.ac,
    required this.security,
    required this.parking,
    required this.laundry,
  });
}

